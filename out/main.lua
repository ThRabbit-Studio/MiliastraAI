local function submit()
    local key = ime_key()
    if key == "" then
        begin_reply(compose_fallback("tooShort", ST.round + 3))
        return
    end
    ST.round = ST.round + 1
    local round = ST.round

    local chosen = nil
    if ST.pick and ST.asks[ST.pick] then
        chosen = ST.asks[ST.pick]
    elseif ST.asks[1] and ST.asks[1].hit then
        chosen = ST.asks[1]
    end

    if chosen then
        logf("MATCH text=%s -> id=%s score=%.3f", key, chosen.id, chosen.score)
    else
        local top = ST.asks[1]
        logf("MISS text=%s（候选 %d 个，最高 %.3f）", key, #ST.asks,
            top and top.score or 0)
    end

    local charCount = utf8_len(key)
    begin_thinking(function()
        if chosen then
            local text = compose(round, chosen.id, charCount)
            if text then return text end
        end
        return compose_fallback("unknown", round)
    end)

    ime_clear()
    on_input_changed()
end

local function on_frame(dt)
    if ST.reveal then
        ST.thinkCount = (ST.thinkCount or 0) + 1
        if ST.thinkCount == 3 then set_text("thinking", "……") end
        if ST.thinkCount >= CFG.THINK_FRAMES then
            local text = ST.reveal()
            ST.reveal = nil
            begin_reply(text or "……")
        end
        return
    end
    if ST.shown < utf8_len(ST.reply) then
        ST.acc = ST.acc + dt
        if ST.acc >= CFG.CHAR_INTERVAL then
            ST.acc = 0
            ST.shown = ST.shown + 1
            set_text("reply", utf8_sub(ST.reply, 1, ST.shown))
        end
        return
    end
    if not ST.thinking then
        ST.busy = false
        set_text("thinking", "")
        refresh_hint()
        script:EnableUpdate(false)
    end
end

