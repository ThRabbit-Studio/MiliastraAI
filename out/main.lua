-- §4 工具函数（引擎会用到，所以放在引擎前面） -------------------------------

local function clamp01(v)
    if v < 0 then return 0 end
    if v > 1 then return 1 end
    return v
end

local function utf8_chars(s)
    local out, i, n = {}, 1, #s
    while i <= n do
        local b = s:byte(i)
        local step
        if b < 0x80 then step = 1
        elseif b < 0xE0 then step = 2
        elseif b < 0xF0 then step = 3
        else step = 4 end
        if i + step - 1 > n then step = n - i + 1 end
        out[#out + 1] = s:sub(i, i + step - 1)
        i = i + step
    end
    return out
end

local function utf8_len(s)
    return #utf8_chars(s)
end

local function utf8_sub(s, from, to)
    local cs = utf8_chars(s)
    to = to or #cs
    if from < 1 then from = 1 end
    if to > #cs then to = #cs end
    local out = {}
    for i = from, to do
        if cs[i] then out[#out + 1] = cs[i] end
    end
    return table.concat(out)
end

local function utf8_last(s, k)
    local cs = utf8_chars(s)
    k = k or 1
    if k >= #cs then return s end
    return table.concat(cs, "", #cs - k + 1, #cs)
end

-- 确定性伪随机：同 seed 同结果，便于离线回归
local function mix_int(x)
    x = math.floor(x)
    if x < 0 then x = -x end
    x = (x ~ 0x9E3779B1) & 0xFFFFFFFF
    x = (x * 0x85EBCA6B) & 0xFFFFFFFF
    x = (x ~ (x >> 13)) & 0xFFFFFFFF
    x = (x * 0xC2B2AE35) & 0xFFFFFFFF
    x = (x ~ (x >> 16)) & 0xFFFFFFFF
    return x
end

local function lcg(seed)
    local state = mix_int(seed) % 2147483647
    if state <= 0 then state = state + 2147483646 end
    return function()
        state = (state * 16807) % 2147483647
        return (state - 1) / 2147483646
    end
end

