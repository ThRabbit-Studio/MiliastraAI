local function register_keys()
    local root = RT.root
    if not root then return end
    -- 要注册的 (事件名, 逻辑键) 对。
    -- 一个逻辑键正常对应一个事件；REMAP 生效时，别名键的事件也会指到这个逻辑键，
    -- 于是一个逻辑键可能挂多个事件（最多两个：自己 + 顶替它的那个键）。
    local pairs_to_bind = {}
    local function consider(physical)
        local ev = event_name(physical)
        if not ev then
            return   -- 没有文档依据的键跳过
        end
        if REMAP_ENABLED and REMAP[physical] then
            -- 这个键被指派去顶替别人了，它自己的事件不再响应
            return
        end
        pairs_to_bind[#pairs_to_bind + 1] = { ev = ev, key = physical }
    end
    for physical in pairs(KEY_INDEX) do
        consider(physical)
    end
    -- 移动/技能/交互/落下键也要注册（它们承载 A S W D E Q R T F X 这 10 个字母）
    for physical in pairs(EXTRA_EVENTS) do
        consider(physical)
    end
    -- 重映射：让别名键的事件去执行被顶替键的功能。
    -- is_alias 标记它必须排在同事件的其它处理器前面（回调返回 true 即视为已处理）。
    if REMAP_ENABLED then
        for unavailable, alias in pairs(REMAP) do
            local ev = event_name(alias)
            if ev then
                pairs_to_bind[#pairs_to_bind + 1] =
                    { ev = ev, key = unavailable, is_alias = true }
            else
                logf("重映射无效：别名键 %s 没有对应事件（被顶替的键 %s）",
                    tostring(alias), tostring(unavailable))
            end
        end
    end
    local bound = {}
    for _, item in ipairs(pairs_to_bind) do
        local tag = item.ev .. "|" .. item.key
        if not bound[tag] then
            bound[tag] = true
            local logical = item.key
            local function cb()
                local ok, handled = pcall(handle_key, logical)
                if not ok then
                    logf("按键处理异常 key=%s err=%s", logical, tostring(handled))
                    return false
                end
                return handled
            end
            local ok = pcall(root.AddKeyEventListener, root, item.ev, cb)
            if ok then
                RT.keyHandlers[#RT.keyHandlers + 1] = { ev = item.ev, cb = cb }
                RT.handlers[item.ev] = RT.handlers[item.ev] or {}
                local bucket = RT.handlers[item.ev]
                if item.is_alias then
                    -- 重映射的处理器必须排在前面：
                    -- 同一个事件可能同时挂着「这个键自己」和「它顶替的那个键」两个处理器，
                    -- 而回调返回 true 表示事件已被处理。谁先谁后决定按它算哪个键。
                    -- REMAP 明确说了这个键要顶替谁，所以让它优先。
                    table.insert(bucket, 1, cb)
                    logf("重映射生效：按 %s 当 %s 用", item.ev, logical)
                else
                    bucket[#bucket + 1] = cb
                end
            end
        end
    end
    local n_remap = 0
    for _ in pairs(REMAP) do n_remap = n_remap + 1 end
    logf("已注册按键监听 %d 个（重映射 %d 条）", #RT.keyHandlers, n_remap)
end

-- §9 布局与装配 --------------------------------------------------------------

-- 布局意图：以画布左上角为原点、y 向下（单位设计像素）。
-- 千星设计坐标原点在左下、y 向上，所以真机上要翻转；这里写的是直觉坐标，
-- 一眼能看出「谁在上面」，不会再出现把控件画到屏幕外的情况。
local LAYOUT = {
    panel_cy = 170, panel_w = 1760, panel_h = 200,
    reply_dx = -20, reply_dy = 0, reply_w = 1680, reply_h = 150,
    think_dx = 620, think_dy = 70,
    comp_cy = 380, comp_w = 1760, comp_h = 70,
    cc_cy = 480, cc_w = 106, cc_h = 50, cc_gap = 8,
    ak_cy = 570, ak_w = 160, ak_h = 46, ak_gap = 8,
    hint_y = 690,
    keys_y = 780,
}

function layout_plan(canvas_w, canvas_h)
    canvas_w = canvas_w or CFG.DESIGN_W
    canvas_h = canvas_h or CFG.DESIGN_H
    local sx = canvas_w / CFG.DESIGN_W
    local sy = canvas_h / CFG.DESIGN_H
    local function dx(x) return x * sx end
    local function dy(y) return canvas_h - y * sy end

    local plan = {}
    local cx = dx(CFG.DESIGN_W / 2)
    local panel_y = dy(LAYOUT.panel_cy)
    plan[#plan + 1] = { name = "panel", parent = nil, kind = "panel",
        x = cx, y = panel_y, w = LAYOUT.panel_w * sx, h = LAYOUT.panel_h * sy }
    plan[#plan + 1] = { name = "reply", parent = "panel", kind = "text", size = 30,
        x = cx + dx(LAYOUT.reply_dx), y = panel_y + LAYOUT.reply_dy * sy,
        w = LAYOUT.reply_w * sx, h = LAYOUT.reply_h * sy,
        text = "", align = "left", color = "text" }
    plan[#plan + 1] = { name = "thinking", parent = "panel", kind = "text", size = 22,
        x = cx + dx(LAYOUT.think_dx), y = panel_y + LAYOUT.think_dy * sy,
        w = 320 * sx, h = 44 * sy, text = "", align = "right", color = "edge" }

    local comp_y = dy(LAYOUT.comp_cy)
    plan[#plan + 1] = { name = "compbar", parent = nil, kind = "panel",
        x = cx, y = comp_y, w = LAYOUT.comp_w * sx, h = LAYOUT.comp_h * sy }
    plan[#plan + 1] = { name = "input", parent = "compbar", kind = "text", size = 30,
        x = cx, y = comp_y, w = (LAYOUT.comp_w - 40) * sx, h = (LAYOUT.comp_h - 8) * sy,
        text = "", align = "middle", color = "text" }

    local function row(prefix, tprefix, count, w, h, gap, cy)
        local total = count * w + (count - 1) * gap
        local start = CFG.DESIGN_W / 2 - total / 2 + w / 2
        for i = 1, count do
            local x = dx(start + (i - 1) * (w + gap))
            local y = dy(cy)
            plan[#plan + 1] = { name = prefix .. i, parent = nil, kind = "panel",
                x = x, y = y, w = w * sx, h = h * sy, color = "cand" }
            plan[#plan + 1] = { name = tprefix .. i, parent = prefix .. i, kind = "text",
                size = 24, x = x, y = y, w = (w - 8) * sx, h = h * sy,
                text = "", align = "middle", color = "text" }
        end
    end
    row("cc", "cct", CFG.MAX_CHAR_CAND, LAYOUT.cc_w, LAYOUT.cc_h, LAYOUT.cc_gap, LAYOUT.cc_cy)
    row("ak", "akt", CFG.MAX_ASK_CAND, LAYOUT.ak_w, LAYOUT.ak_h, LAYOUT.ak_gap, LAYOUT.ak_cy)

    plan[#plan + 1] = { name = "hint", parent = nil, kind = "text", size = 22,
        x = cx, y = dy(LAYOUT.hint_y), w = 1760 * sx, h = 48 * sy,
        text = "", align = "middle", color = "dim" }
    plan[#plan + 1] = { name = "keys", parent = nil, kind = "text", size = 18,
        x = cx, y = dy(LAYOUT.keys_y), w = 1760 * sx, h = 44 * sy,
        text = "输入：字母键打拼音 · 1-0 选字或选问法 · Backspace 删除 · "
            .. SEND_KEY .. " 发送",
        align = "middle", color = "dim" }
    return plan, sx, sy
end

local function build_ui()
    local roots = G().GetClientUIRoots()
    if not roots or #roots == 0 then return false end
    unregister_keys()
    destroy_all()
    RT.root = roots[1]

    local cw, ch = G().GetUICanvasSize()
    if cw and cw > 0 then RT.canvasW = cw end
    if ch and ch > 0 then RT.canvasH = ch end

    local plan, sx, sy = layout_plan(RT.canvasW, RT.canvasH)
    local abs_center = {}
    for _, e in ipairs(plan) do
        local px, py = RT.canvasW / 2, RT.canvasH / 2
        if e.parent and abs_center[e.parent] then
            px, py = abs_center[e.parent][1], abs_center[e.parent][2]
        end
        local lx = (e.x - px) / sx
        local ly = (e.y - py) / sy
        local parent_obj = e.parent and RT.nodes[e.parent] or RT.root
        local c
        if e.kind == "panel" then
            local tint = CFG.COLOR_PANEL
            if e.color == "cand" then tint = CFG.COLOR_CAND end
            c = make_panel(e.name, parent_obj, lx, ly, e.w, e.h, tint)
        else
            local tint = CFG.COLOR_TEXT
            if e.color == "dim" then tint = CFG.COLOR_DIM end
            if e.color == "edge" then tint = CFG.COLOR_PANEL_EDGE end
            local align = Enum.TextHorizontalAlignment.Left
            if e.align == "middle" then align = Enum.TextHorizontalAlignment.Middle end
            if e.align == "right" then align = Enum.TextHorizontalAlignment.Right end
            c = make_text(e.name, parent_obj, lx, ly, e.w, e.h,
                e.text or "", e.size or 24, tint, align)
        end
        abs_center[e.name] = { e.x, e.y }
        if e.kind == "panel" and e.color == "cand" and c then c:SetActive(false) end
    end

    register_keys()
    refresh_all()
    logf("UI 就绪 canvas=%dx%d scale=%.3f", RT.canvasW, RT.canvasH, sx)
    return true
end

-- §10 生命周期 ---------------------------------------------------------------

function OnInit()
    if CFG.IMAGE_PREFAB_INDEX == 0 then
        print("GAME FAULT BEGIN E_IME_01")
        print("stage=CONFIG")
        print("reason=图片控件模板索引未填写：IMAGE_PREFAB_INDEX 需要填入创作者提供的索引")
        print("GAME FAULT END E_IME_01")
    end
    local n_chars, n_syl = 0, 0
    for _, list in pairs(MOD.IME_CHARS) do
        n_syl = n_syl + 1
        n_chars = n_chars + #list
    end
    logf("INIT prefab=%d 语料索引=%d 字库=%d字/%d音节 发送键=%s",
        CFG.IMAGE_PREFAB_INDEX, #MOD.BANK, n_chars, n_syl, SEND_KEY)
end

function OnStart()
    if CFG.IMAGE_PREFAB_INDEX == 0 then return end
    RT.retries = 0
    RT.ready = build_ui()
    if not RT.ready then
        script:EnableUpdate(true)
        logf("START 宿主未就绪，进入重试（预算 %d 次）", CFG.READY_RETRY_BUDGET)
    else
        set_text("reply", "有什么想问的，打拼音就行。")
    end
end

function OnEnable()
    logf("ENABLE")
end

function OnDisable()
    unregister_keys()
    logf("DISABLE")
end

function OnUpdate(dt)
    if not RT.ready then
        RT.retries = RT.retries + 1
        if RT.retries > CFG.READY_RETRY_BUDGET then
            script:EnableUpdate(false)
            logf("START 放弃：重试 %d 次仍未就绪", RT.retries)
            return
        end
        RT.ready = build_ui()
        if RT.ready then
            set_text("reply", "有什么想问的，打拼音就行。")
        end
        return
    end
    on_frame(dt)
end

function OnDestroy()
    script:EnableUpdate(false)
    unregister_keys()
    destroy_all()
    logf("DESTROY")
end

