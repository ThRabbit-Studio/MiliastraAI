-- §3 拼音引擎（由构建脚本从 ime/*.lua 内联） --------------------------------

-- [[IME_ENGINE_BEGIN]] 以下内容由 build/build_speech.py 从 ime/ 内联，请勿手改
-- ============================================================================
-- 拼音引擎 · 连续拼音切分
--
-- 玩家打的是连续字母串（"nihao"），要先切成音节（ni + hao）才能查字。
-- 切分策略是**贪心优先匹配**，不是「最优切分」：优先切出长音节，
-- 这样 xian 会切成一个音节（先/现/线…），而不是 xi + an。
-- 这与主流输入法的手感一致，也让同一串字母的切分结果稳定可预期。
--
-- 本文件由 build_speech.py 内联进 main.lua，因此不写 return、不写 require。
-- ============================================================================

-- 引擎自有的数据引用（由 §1 数据段提供）
local IME = {
    syllables = MOD.IME_SYLLABLES or {},
    chars = MOD.IME_CHARS or {},
    -- 音节集合，加速判断
    syl_set = {},
}
for i = 1, #IME.syllables do
    IME.syl_set[IME.syllables[i]] = true
end

-- 某个字符串是不是合法音节
local function ime_is_syllable(s)
    return s ~= nil and s ~= "" and IME.syl_set[s] == true
end

-- 取候选字列表（已按常用度排序）。没有该音节则返回空表。
local function ime_chars_of(syl)
    if syl == nil or syl == "" then return {} end
    return IME.chars[syl] or {}
end

-- 连续拼音 -> 音节数组。返回 (音节表, 已切长度)。
-- 未匹配到音节的尾巴不会出现在结果里，留在 pending 中让玩家继续打。
local function ime_segment(s)
    local out = {}
    local i, n = 1, #s
    while i <= n do
        -- 贪心：先看「当前字符 + 分隔符 + 剩余」里最长的合法音节
        local matched = nil
        local maxLen = math.min(6, n - i + 1)   -- 最长音节 6 个字母（chuang）
        for len = maxLen, 1, -1 do
            local cand = s:sub(i, i + len - 1)
            if ime_is_syllable(cand) then
                matched = cand
                i = i + len
                break
            end
        end
        if not matched then
            break
        end
        out[#out + 1] = matched
    end
    return out, i - 1
end

-- 诊断用：把切分结果拼成 "ni|hao" 便于日志排查
local function ime_segment_str(segs)
    return table.concat(segs, "|")
end

-- ============================================================================
-- 拼音引擎 · 汉字识别
--
-- 为什么不直接用 Lua 的字符类 [一-鿿]：
--   字符类是否按「字符」还是按「字节」解释，取决于 Lua 版本与 locale。
--   本项目的离线验证台用的是 lupa 内嵌 Lua 5.5 + 默认 locale，实测它按**字节**
--   处理，会把一个汉字切成两三个假字符，导致匹配打分完全错乱。
--   真机是 Lua 5.3，行为可能不同——这种「取决于环境」的东西不能当地基。
-- 所以这里显式解码 UTF-8 码点再判断范围，行为与语言环境无关。
--
-- 本文件由 build_speech.py 内联进 main.lua，不写 return / require。
-- ============================================================================

-- 逐个返回 UTF-8 字符及其码点：迭代器给出 (字符, 码点)
local function utf8_iter(s)
    local i, n = 1, #s
    return function()
        if i > n then return nil end
        local b = s:byte(i)
        local len, cp
        if b < 0x80 then
            len, cp = 1, b
        elseif b < 0xE0 then
            len = 2
            cp = (b - 0xC0) * 0x40 + ((s:byte(i + 1) or 0x80) - 0x80)
        elseif b < 0xF0 then
            len = 3
            cp = (b - 0xE0) * 0x1000
                + ((s:byte(i + 1) or 0x80) - 0x80) * 0x40
                + ((s:byte(i + 2) or 0x80) - 0x80)
        else
            len = 4
            cp = (b - 0xF0) * 0x40000
                + ((s:byte(i + 1) or 0x80) - 0x80) * 0x1000
                + ((s:byte(i + 2) or 0x80) - 0x80) * 0x40
                + ((s:byte(i + 3) or 0x80) - 0x80)
        end
        local ch = s:sub(i, i + len - 1)
        i = i + len
        return ch, cp
    end
end

-- 只保留汉字（CJK 统一表意文字基本区），返回「字 -> 出现次数」与总字数
local function han_counts(s)
    local cnt, total = {}, 0
    for ch, cp in utf8_iter(s) do
        if cp >= 0x4E00 and cp <= 0x9FFF then
            cnt[ch] = (cnt[ch] or 0) + 1
            total = total + 1
        end
    end
    return cnt, total
end

-- 只要汉字列表（按出现顺序，含重复）
local function han_list(s)
    local out = {}
    for ch, cp in utf8_iter(s) do
        if cp >= 0x4E00 and cp <= 0x9FFF then out[#out + 1] = ch end
    end
    return out
end

-- ============================================================================
-- 拼音引擎 · 输入成句（词级优先）
--
-- 为什么是词级：单字级拼音无法消歧。打 ming 时候选里既有「名」也有「命」，
-- 只按单字频次排会把「命」放前面；但「mingzi」作为词就唯一指向「名字」。
-- 所以刷新候选时先做词级匹配（最长 4 音节），匹配不到才退回单字级。
--
-- 单字级再叠一层上下文消歧：玩家刚定下的那个字，如果能和某候选字在语料里
-- 成词，就把它提前（靠 MOD.IME_BIGRAMS 这张搭配表）。
--
-- 状态：
--   raw        还没定字的拼音字母
--   committed  已经定下来的汉字
--   pool       当前候选（可能是词也可能是单字）
--   pool_span  选中一个候选会吃掉几个音节
--
-- 本文件由 build_speech.py 内联进 main.lua，不写 return / require。
-- ============================================================================

local IMEST = {
    raw = "",
    committed = "",
    segs = {},
    pool = {},
    pool_kind = "char",
    pool_span = 1,
    -- 候选池上限。UI 只显示前 10 个（数字键 1-0），但池子要留得更宽：
    -- 实测「失」在 shi 里排第 14，池子截到 12 就选不到它了。
    maxp = 48,
}

-- 词级匹配：从长到短试，最长 4 个音节。
-- 必须满足「词的拼音串 == 这几个音节拼起来的串」，这样才不会把
-- xian（一个音节）误当成 xi + an（两个音节）。
local function ime_word_match(segs)
    local table_words = MOD.IME_WORDS
    if table_words == nil then return nil, 0 end
    local n = #segs
    for span = math.min(4, n), 2, -1 do
        local key = table.concat(segs, "", 1, span)
        local words = table_words[key]
        if words and #words > 0 then
            return words, span
        end
    end
    return nil, 0
end

-- 上下文消歧：按「上一个字 + 候选字」在语料问法里的搭配分重排单字候选。
-- 两段式：先看「有没有搭配记录」，没有记录的一律排后面；都有记录的再比搭配分。
-- 为什么不用纯搭配分排序：搭配分整体很小（问法只有 126 条），
-- 如果直接拿分数当主键，会把单字表里本来很靠前的常用字压下去。
local function ime_context_order(base, prev_char)
    local bigrams = MOD.IME_BIGRAMS
    if prev_char == "" or bigrams == nil then return base end
    local rank_of = bigrams[prev_char]
    if rank_of == nil then return base end
    local scored = {}
    for i = 1, #base do
        local bonus = rank_of[base[i]]
        scored[#scored + 1] = {
            ch = base[i],
            known = (bonus ~= nil) and 1 or 0,
            bonus = bonus or 0,
            idx = i,
        }
    end
    table.sort(scored, function(a, b)
        if a.known ~= b.known then return a.known > b.known end
        if a.bonus ~= b.bonus then return a.bonus > b.bonus end
        return a.idx < b.idx
    end)
    local out = {}
    for i = 1, #scored do out[i] = scored[i].ch end
    return out
end

-- 重新切分并刷新候选。raw 每次变化后都要调用。
local function ime_refresh()
    local segs, _used = ime_segment(IMEST.raw)
    IMEST.segs = segs
    IMEST.pool = {}
    IMEST.pool_kind = "char"
    IMEST.pool_span = 1
    if #segs == 0 then return 0 end

    -- 1) 词级
    local words, span = ime_word_match(segs)
    if words then
        local pool = {}
        for i = 1, math.min(#words, IMEST.maxp) do pool[i] = words[i] end
        IMEST.pool = pool
        IMEST.pool_kind = "word"
        IMEST.pool_span = span
        return #pool
    end

    -- 2) 单字级 + 上下文消歧
    local base = ime_chars_of(segs[1])
    local prev = ""
    if #IMEST.committed > 0 then
        prev = utf8_last(IMEST.committed, 1)
    end
    base = ime_context_order(base, prev)
    local pool = {}
    for i = 1, math.min(#base, IMEST.maxp) do pool[i] = base[i] end
    IMEST.pool = pool
    return #pool
end

-- 拼音缓冲过长时只保留最近的部分（并返回丢掉了多少字符）
local function ime_trim(max_raw)
    local cut = 0
    if #IMEST.raw > max_raw then
        cut = #IMEST.raw - max_raw
        IMEST.raw = IMEST.raw:sub(cut + 1)
        ime_refresh()
    end
    return cut
end

-- 追加字母（只接受 a-z / A-Z）
local function ime_letter(ch)
    if ch == nil or #ch ~= 1 then return false end
    local b = ch:byte()
    local lower = (b >= 65 and b <= 90) and string.char(b + 32) or ch
    if not lower:match("^[a-z]$") then return false end
    IMEST.raw = IMEST.raw .. lower
    ime_trim(24)
    ime_refresh()
    return true
end

-- 退格：优先退未定字的字母；字母退完了再退已定的汉字
local function ime_backspace()
    if #IMEST.raw > 0 then
        IMEST.raw = IMEST.raw:sub(1, #IMEST.raw - 1)
        ime_refresh()
        return "raw"
    end
    if #IMEST.committed > 0 then
        IMEST.committed = utf8_sub(IMEST.committed, 1, utf8_len(IMEST.committed) - 1)
        ime_refresh()
        return "committed"
    end
    return nil
end

-- 选候选。idx 从 1 开始。
-- 词候选会吃掉 pool_span 个音节，单字候选吃一个。
local function ime_pick(idx)
    local item = IMEST.pool[idx]
    if item == nil then return nil end
    local span = IMEST.pool_span
    if span < 1 then span = 1 end
    -- 从 raw 头部去掉这些音节的字母
    local cut = 0
