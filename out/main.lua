local function event_name(physical)
    -- 移动/技能/交互/落下键：它们不在「奇匠按键」编号体系里，事件名单独列
    if EXTRA_EVENTS[physical] then return EXTRA_EVENTS[physical] end
    local idx = KEY_INDEX[physical]
    if not idx then return nil end
    -- 文档 §26(3) 里只有 KeyboardCraftspersonKey1Down ~ Key43Down。
    -- ⚠ 不要再写 Key46Down：文档里没有这个事件，那是我早先凭印象编的。
    return "KeyboardCraftspersonKey" .. idx .. "Down"
end

-- 逻辑键 -> 该注册哪些事件名。
-- 默认就是它自己；如果 REMAP 里把它指向了别的键，就把两边的监听都注册上：
-- 这样无论真机最终给的是哪个键的事件，逻辑上都能收到。
local function events_for(physical)
    local names = {}
    local own = event_name(physical)
    if own then names[#names + 1] = own end
    if REMAP_ENABLED then
        local alias = REMAP[physical]
        if alias then
            local a = event_name(alias)
            if a and a ~= own then names[#names + 1] = a end
        end
    end
    -- 反向：如果别的键把功能指向了我，我也要接住它的事件
    if REMAP_ENABLED then
        for from, to in pairs(REMAP) do
            if to == physical then
                local a = event_name(from)
                if a then
                    local dup = false
                    for _, n in ipairs(names) do if n == a then dup = true end end
                    if not dup then names[#names + 1] = a end
                end
            end
        end
    end
    return names
end

-- 事件名 -> 该按哪个逻辑键处理。
-- 一个事件可能对应多个逻辑键（重映射之后），所以要返回列表：
-- 处理时按顺序试，谁能处理就归谁。
local function logical_keys_for(event)
    local out = {}
    local idx = tonumber(event:match("^KeyboardCraftspersonKey(%d+)Down$"))
    if not idx then return out end
    local physical = INDEX_TO_KEY[idx]
    if not physical then return out end
    out[#out + 1] = physical
    if REMAP_ENABLED then
        -- 这个物理键被指派去顶替谁
        for from, to in pairs(REMAP) do
            if to == physical then out[#out + 1] = from end
        end
    end
    return out
end

local function handle_key(physical)
    if physical == SEND_KEY then
        submit()
        return true
    end

    -- 数字键：先用于选字（有候选汉字时），否则用于选问法
    local digit = DIGIT_ORDER[physical]
    if digit then
        local ch = ime_pool()[digit]
        if ch then
            ime_pick(digit)
            on_input_changed()
            return true
        end
        if ST.asks[digit] then
            ST.pick = digit
            refresh_asks()
            logf("SELECT ask idx=%d id=%s", digit, ST.asks[digit].id)
            submit()
            return true
        end
        return true
    end

    if physical == "BACKSPACE" then
        ime_backspace()
        on_input_changed()
        return true
    end

    -- 字母键：查「字母 -> 物理键」的反表。
    -- 22 个字母是它们本来那个键；B/C/M/N 在文档里没有按键，补在 F5-F8 上。
    local ch = nil
    for letter, phys in pairs(LETTER_KEY) do
        if phys == physical then ch = letter break end
    end
    if ch then
        ime_letter(ch)
        on_input_changed()
        return true
    end
    return false
end

