-- §5 答句生成 ----------------------------------------------------------------

local CLAUSE_END = { "。", "！", "？", "；", "…", ".", "!", "?", ";", "　" }

local function split_clauses(text)
    local out, buf, i, n = {}, {}, 1, #text
    while i <= n do
        local ch = text:sub(i, i)
        local b = ch:byte()
        local step = 1
        if b >= 0xF0 then step = 4 elseif b >= 0xE0 then step = 3 elseif b >= 0xC0 then step = 2 end
        local piece = text:sub(i, i + step - 1)
        buf[#buf + 1] = piece
        for _, e in ipairs(CLAUSE_END) do
            if piece == e then
                out[#out + 1] = table.concat(buf)
                buf = {}
                break
            end
        end
        i = i + step
    end
    if #buf > 0 then out[#out + 1] = table.concat(buf) end
    return out
end

local lastTagIndex = nil

-- 以某个变体为骨架，开头句在不同变体之间轮换。
-- 语料里的变体经常共享结尾、只换开头，所以不能直接拼两个变体（读起来像缝合）。
local function compose(seed, id, charCount)
    local vars = MOD.ANSWERS[id]
    if not vars or #vars == 0 then return nil end
    local rnd = lcg(seed)
    local pick = 1 + math.floor(rnd() * #vars)
    local variant = vars[pick]
    if variant == nil then variant = vars[1] end

    local heads, seen = {}, {}
    for _, v in ipairs(vars) do
        local cs = split_clauses(v)
        local head = cs[1]
        if head and not seen[head] then
            seen[head] = true
            heads[#heads + 1] = head
        end
    end
    if #heads == 0 then return variant end

    local base = split_clauses(variant)
    local head = base[1]
    if #heads > 1 then
        local idx = 1 + math.floor(rnd() * #heads)
        if heads[idx] == head then idx = idx % #heads + 1 end
        head = heads[idx]
    end

    local parts = {}
    local quirk = math.floor(rnd() * 3)
    local confirm = MOD.PERSONA.confirm
    if confirm and #confirm > 0 and (charCount or 0) > 0 and charCount <= 3 and quirk == 0 then
        local idx = 1 + math.floor(rnd() * #confirm)
        if idx == lastTagIndex and #confirm > 1 then idx = idx % #confirm + 1 end
        lastTagIndex = idx
        parts[#parts + 1] = confirm[idx]
    end
    parts[#parts + 1] = head
    for i = 2, #base do parts[#parts + 1] = base[i] end
    return table.concat(parts)
end

local function compose_fallback(kind, seed)
    local rnd = lcg(seed)
    local pool = MOD.PERSONA[kind]
    if not pool or #pool == 0 then pool = MOD.PERSONA.unknown end
    return pool[1 + math.floor(rnd() * #pool)]
end

